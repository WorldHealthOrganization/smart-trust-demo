#!/usr/bin/env bun
/**
 * Renders the module × journey-step map of the DPI-H policy-maker track:
 * which module (M1–M7) meets which journey step (J1–J4.1), and what is
 * technical and what is policy where they meet.
 *
 * | input | what it gives |
 * |---|---|
 * | `workshops/dpi-h-policy-track.workshop.json` | modules, and the steps where each module's question is asked (`asked` cells) |
 * | `workshops/module-journey-map.json` | the text of every cell, the `draws` cells, and the cross-module overlaps |
 *
 * Writes `input/pagecontent/module-journey-map.md`; `--check` fails if that
 * page is stale or if an asked cell has no text.
 */
import { readFileSync, writeFileSync } from "node:fs";

type Cell = { module: string; step: string; kind?: "draws"; technical: string; policy: string };
type Overlap = { label: string; modules: string[]; steps: string[]; text: string };
type MapFile = { columns: string[]; cells: Cell[]; overlaps: { technical: Overlap[]; policy: Overlap[] } };

const WS = "workshops/dpi-h-policy-track.workshop.json";
const MAP = "workshops/module-journey-map.json";
const OUT = "input/pagecontent/module-journey-map.md";

const ws = JSON.parse(readFileSync(WS, "utf8"));
const map: MapFile = JSON.parse(readFileSync(MAP, "utf8"));
const modules: { id: string; title: string; carries?: string; sheet?: string }[] = ws.modules;
const steps: { scenario: string; step: string }[] = ws.steps;

const asked = new Set<string>();
for (const s of steps) for (const q of s.questions ?? []) asked.add(`${q.module}|${s.step}`);

const errors: string[] = [];
const cellAt = new Map(map.cells.map((c) => [`${c.module}|${c.step}`, c]));
for (const k of asked) if (!cellAt.has(k)) errors.push(`asked at ${k.replace("|", " × ")} but no cell in ${MAP}`);
for (const c of map.cells) {
  const k = `${c.module}|${c.step}`;
  if (!map.columns.includes(c.step)) errors.push(`cell ${k}: step ${c.step} is not a column`);
  if (!modules.some((m) => m.id === c.module)) errors.push(`cell ${k}: no module ${c.module}`);
  if (c.kind !== "draws" && !asked.has(k)) errors.push(`cell ${k} is marked asked, but the workshop asks no ${c.module} question at ${c.step}`);
  if (c.kind === "draws" && asked.has(k)) errors.push(`cell ${k} is marked draws, but the workshop asks a ${c.module} question there`);
}
if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}

const scenarioOf = new Map(steps.map((s) => [s.step, s.scenario]));
const sheet = (id?: string) => (id ? id.replace("sheet-", "Sheet ") : "");
const cellMark = (m: string, s: string) => {
  const c = cellAt.get(`${m}|${s}`);
  return !c ? "" : c.kind === "draws" ? "○" : "●";
};

const lines: string[] = [];
lines.push(
  "<!-- Generated by tools/workshop/module-journey-map.ts from workshops/module-journey-map.json and workshops/dpi-h-policy-track.workshop.json. Do not edit by hand. -->",
  "",
  "Each module of the policy-maker track asks one question of the same story. This page shows where each module (M1 to M7) meets a step of the journeys (J1 to J4.1), and what is **technical** and what is **policy** at that meeting point. The same map is the *Modules × journey* step of the journeys viewer's Discussion tab.",
  "",
  "● = the module's question is asked at this step in the walkthrough. ○ = the module draws on this step without asking there.",
  "",
  "### The map",
  "",
  `| Module | Sheet | ${map.columns.join(" | ")} |`,
  `|---|---|${map.columns.map(() => ":-:").join("|")}|`,
);
for (const m of modules) lines.push(`| **${m.id}** ${m.title} | ${sheet(m.sheet)} | ${map.columns.map((s) => cellMark(m.id, s)).join(" | ")} |`);
lines.push("{: .grid }", "");

lines.push("### Where they meet", "");
for (const m of modules) {
  const cells = map.columns.map((s) => cellAt.get(`${m.id}|${s}`)).filter((c): c is Cell => !!c);
  if (!cells.length) continue;
  lines.push(`#### ${m.id} · ${m.title}`, "");
  if (m.carries) lines.push(`*${m.carries}*`, "");
  lines.push("| Step | | Technical | Policy |", "|---|:-:|---|---|");
  for (const c of cells) lines.push(`| ${c.step} | ${c.kind === "draws" ? "○" : "●"} | ${c.technical} | ${c.policy} |`);
  lines.push("{: .grid }", "");
}

const overlap = (title: string, lede: string, xs: Overlap[]) => {
  lines.push(`### ${title}`, "", lede, "", "| Thread | Modules | Steps | How it crosses |", "|---|---|---|---|");
  for (const o of xs) lines.push(`| **${o.label}** | ${o.modules.join(", ")} | ${o.steps.join(", ")} | ${o.text} |`);
  lines.push("{: .grid }", "");
};
overlap("Technical overlaps", "Components that more than one module and more than one step depend on: build or test them once.", map.overlaps.technical);
overlap("Policy overlaps", "Decisions and legal bases that more than one module and step force: decide them once, with one holder.", map.overlaps.policy);

lines.push(
  "### Sources",
  "",
  `The steps and the questions asked at them are the workshop's (\`${WS}\`); the journeys are ${[...new Set(scenarioOf.values())].map((s) => `\`${s}\``).join(", ")}. The cell text and the overlaps are in \`${MAP}\`.`,
  "",
);

const out = lines.join("\n");
if (process.argv.includes("--check")) {
  let cur = "";
  try {
    cur = readFileSync(OUT, "utf8");
  } catch {}
  if (cur !== out) {
    console.error(`${OUT} is stale: run bun tools/workshop/module-journey-map.ts`);
    process.exit(1);
  }
  console.log(`${OUT} is current`);
} else {
  writeFileSync(OUT, out);
  console.log(`wrote ${OUT}`);
}
