#!/usr/bin/env bun
/**
 * The workshop's module pages on the IG (option A of the owner's choice,
 * 2026-11-16): a hub, one page per policy module (M1–M7) and one per
 * technical module (T1–T7, placeholders until written), with a switch
 * between the two tracks on every page.
 *
 * | input | what it gives |
 * |---|---|
 * | `workshops/dpi-h-policy-track.workshop.json` | the policy modules, their sheets, and the questions asked at each step |
 * | `workshops/technical-track.json` | the technical modules, each paired with a policy module |
 * | `workshops/country-canvas.json` | each canvas sheet's parts, minutes and preview |
 * | `workshops/module-journey-map.json` | where each module meets each step, technical and policy |
 * | `workshops/glossary-use.json`, `glossary/dpi-h-policy-track.glossary.json` | the terms at each step |
 * | `scenarios/user-scenarios/*.json` | each step's title |
 *
 * Writes `input/pagecontent/workshop.md`, `workshop-m<n>.md` and
 * `workshop-t<n>.md`. `--check` fails if any is stale.
 */
import { readFileSync, writeFileSync, readdirSync } from "node:fs";

const read = (p: string) => JSON.parse(readFileSync(p, "utf8"));
const ws = read("workshops/dpi-h-policy-track.workshop.json");
const tech = read("workshops/technical-track.json");
const canvas = read("workshops/country-canvas.json");
const map = read("workshops/module-journey-map.json");
const use = read("workshops/glossary-use.json");
const glossary = read("glossary/dpi-h-policy-track.glossary.json");

type Mod = { id: string; title: string; day?: number; carries?: string; sheet?: string };
const mods: Mod[] = ws.modules;
const tmods: { id: string; pairedWith: string; day: number; title: string; carries?: string; status: string }[] = tech.modules;
const sheets = new Map<string, any>(canvas.sheets.map((s: any) => [s.id, s]));
const terms = new Map<string, any>(glossary.terms.map((t: any) => [t.id, t]));
const steps: { scenario: string; step: string; questions?: { module: string; text: string }[] }[] = ws.steps;

const stepTitle = new Map<string, string>();
for (const f of readdirSync("scenarios/user-scenarios")) {
  const s = read(`scenarios/user-scenarios/${f}`);
  for (const st of s.steps ?? []) if (st.id && st.title) stepTitle.set(st.id, st.title);
}
const VIEWER = "en/smart-trust-demo/journeys/smart-trust-demo/workshops/dpi-h-policy-track/";
const DAYS: Record<number, string> = { 1: "Day 1 · 30 November", 2: "Day 2 · 1 December" };
const page = (id: string) => `workshop-${id.toLowerCase()}.html`;
const stepLink = (s: string) => `[${s}](${VIEWER}walkthrough/${s}/)`;
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
const HEAD = (src: string) => `<!-- Generated by tools/workshop/module-pages.ts from ${src}. Do not edit by hand. -->\n`;

const errors: string[] = [];
for (const t of tmods) if (!mods.some((m) => m.id === t.pairedWith)) errors.push(`technical-track.json: ${t.id} pairs with no module ${t.pairedWith}`);
for (const m of mods) if (m.sheet && !sheets.has(m.sheet)) errors.push(`country-canvas.json: no ${m.sheet} for ${m.id}`);
if (errors.length) (console.error(errors.join("\n")), process.exit(1));

/** The two tracks, one row per day, the current module in bold. */
function strip(current: string): string {
  const row = (list: { id: string; day?: number }[], label: string) =>
    `**${label}:** ` +
    [1, 2]
      .map((d) => `${DAYS[d]!.split(" · ")[0]} ${list.filter((m) => m.day === d).map((m) => (m.id === current ? `**${m.id}**` : `[${m.id}](${page(m.id)})`)).join(" · ")}`)
      .join(" &nbsp;|&nbsp; ");
  return `${row(mods, "Policy track")}  \n${row(tmods, "Technical track")}`;
}
function trackSwitch(id: string): string {
  const isT = id.startsWith("T");
  const pair = isT ? tmods.find((t) => t.id === id)!.pairedWith : tmods.find((t) => t.pairedWith === id)?.id;
  return isT
    ? `[Policy track: ${pair}](${page(pair!)}) · **Technical track: ${id}**`
    : `**Policy track: ${id}** · ${pair ? `[Technical track: ${pair}](${page(pair)})` : "Technical track: none yet"}`;
}
const cellsOf = (m: string) => (map.cells as any[]).filter((c) => c.module === m);
const termsAt = (stepIds: string[]) => [...new Set(stepIds.flatMap((s) => use.steps[s] ?? []))].filter((id) => terms.has(id));
const termLine = (ids: string[]) =>
  ids.map((id) => `[${terms.get(id).notation && terms.get(id).notation !== terms.get(id).prefLabel ? terms.get(id).notation : terms.get(id).prefLabel}](glossary.html#term-${id})`).join(" · ");

const files: Record<string, string> = {};

// ── the hub ─────────────────────────────────────────────────────────────
{
  const L: string[] = [HEAD("workshops/ (the workshop, the technical track, the canvas, the module map)")];
  L.push(
    "The DPI-H for Health workshop runs two tracks over two days, both taught from the same journey of one cross-border family. Each policy module asks one question of the journey and fills one sheet of the [Country Canvas](country-canvas.html). Each technical module is paired with the policy module of the same number. Switch tracks on any module page.",
    "",
    "**Policy track** · [Technical track](#technical-track) · [Module × journey map](module-journey-map.html) · [Glossary](glossary.html) · [Journeys viewer](" + VIEWER + "overview/)",
    "",
    "### Policy track",
    "",
  );
  for (const d of [1, 2]) {
    L.push(`#### ${DAYS[d]}`, "", "| Module | Sheet | The question it carries | Journey steps |", "|---|---|---|---|");
    for (const m of mods.filter((x) => x.day === d)) {
      const sh = sheets.get(m.sheet!);
      const asked = cellsOf(m.id).filter((c) => c.kind !== "draws").map((c) => c.step);
      L.push(`| [**${m.id}** ${cell(m.title)}](${page(m.id)}) | ${sh ? `Sheet ${sh.n}` : ""} | ${cell(m.carries ?? "")} | ${asked.join(", ")} |`);
    }
    L.push("{: .grid }", "");
  }
  L.push("### Technical track", "", "The technical modules are **placeholders**: they are not written yet. Each is paired with a policy module.", "", "| Module | Day | Paired with | Status |", "|---|---|---|---|");
  for (const t of tmods) L.push(`| [**${t.id}** ${cell(t.title)}](${page(t.id)}) | ${t.day} | [${t.pairedWith}](${page(t.pairedWith)}) | ${t.status === "placeholder" ? "Placeholder" : "Ready"} |`);
  L.push("{: .grid }", "");
  files["input/pagecontent/workshop.md"] = L.join("\n");
}

// ── a policy module ─────────────────────────────────────────────────────
for (const m of mods) {
  const n = m.id.slice(1);
  const sh = sheets.get(m.sheet!)!;
  const parts = sh.parts.filter((p: any) => p.module === m.id);
  const cs = cellsOf(m.id);
  const asked = cs.filter((c) => c.kind !== "draws");
  const draws = cs.filter((c) => c.kind === "draws");
  const qs = steps.flatMap((s) => (s.questions ?? []).filter((q) => q.module === m.id).map((q) => ({ step: s.step, text: q.text })));
  const L: string[] = [HEAD("workshops/dpi-h-policy-track.workshop.json, country-canvas.json, module-journey-map.json and glossary-use.json")];
  L.push(trackSwitch(m.id), "", strip(m.id), "", `**Day ${m.day} · Module ${n} · fills Sheet ${sh.n}${sh.parts.some((p: any) => p.module !== m.id) ? ` (with ${[...new Set(sh.parts.filter((p: any) => p.module !== m.id).map((p: any) => p.module))].join(", ")})` : ""}**`, "");
  if (m.carries) L.push(`> *${m.carries}*`, "");
  L.push(`### On the canvas: Sheet ${sh.n} · ${sh.title}`, "", `<img src="${sh.preview}" alt="Country Canvas Sheet ${sh.n}: ${sh.title}" style="width:100%;max-width:900px;border:1px solid #ccc"/>`, "");
  L.push("| Part | Time | What the table does |", "|---|---|---|");
  for (const p of parts) L.push(`| **${cell(p.title)}** | ${p.minutes ? `${p.minutes} min` : ""} | ${cell(p.what)} |`);
  L.push("{: .grid }", "", `[The whole canvas](country-canvas.html) · [Word file (A3)](${canvas.docx}) · [PDF](${canvas.pdf})`, "");
  L.push("### Where it meets the journey", "", "| Step | Technical | Policy |", "|---|---|---|");
  for (const c of asked) L.push(`| ● ${stepLink(c.step)} ${cell(stepTitle.get(c.step) ?? "")} | ${cell(c.technical)} | ${cell(c.policy)} |`);
  L.push("{: .grid }", "");
  if (draws.length) L.push(`Also draws on: ${draws.map((c: any) => `○ ${stepLink(c.step)} (${c.policy.replace(/\.$/, "")})`).join("; ")}.`, "");
  if (qs.length) {
    L.push("### Questions for the table", "");
    for (const q of qs) L.push(`- ${q.text} (${stepLink(q.step)})`);
    L.push("");
  }
  const tl = termsAt(asked.map((c) => c.step));
  if (tl.length) L.push("### Terms you will hear", "", termLine(tl), "");
  L.push("### Elsewhere", "", `[${m.id} in the journeys viewer](${VIEWER}${m.id.toLowerCase()}/) · [Discussion](${VIEWER}discuss/) · [Module × journey map](module-journey-map.html) · [All modules](workshop.html)`, "");
  files[`input/pagecontent/workshop-${m.id.toLowerCase()}.md`] = L.join("\n");
}

// ── a technical module (placeholder) ────────────────────────────────────
for (const t of tmods) {
  const m = mods.find((x) => x.id === t.pairedWith)!;
  const asked = cellsOf(m.id).filter((c) => c.kind !== "draws");
  const L: string[] = [HEAD("workshops/technical-track.json and module-journey-map.json")];
  L.push(trackSwitch(t.id), "", strip(t.id), "", `**Day ${t.day} · ${t.id} · paired with [${m.id} ${m.title}](${page(m.id)})**`, "");
  if (t.status === "placeholder") L.push(`> **Placeholder.** ${t.id} is not written yet. Until it is, this page shows what its paired policy module asks of the technical side, as starting material.`, "");
  if (t.carries) L.push(`> *${t.carries}*`, "");
  L.push(`### What ${m.id} asks of the technical side`, "", "| Step | Technical |", "|---|---|");
  for (const c of asked) L.push(`| ${stepLink(c.step)} ${cell(stepTitle.get(c.step) ?? "")} | ${cell(c.technical)} |`);
  L.push("{: .grid }", "");
  const tl = termsAt(asked.map((c) => c.step));
  if (tl.length) L.push("### Terms at those steps", "", termLine(tl), "");
  L.push("### To be written", "", "- The question this module carries", "- Its objectives and timings", "- Which canvas sheet, if any, it fills", "- The journey steps it teaches from", "", `[All modules](workshop.html)`, "");
  files[`input/pagecontent/workshop-${t.id.toLowerCase()}.md`] = L.join("\n");
}

let stale = 0;
for (const [p, c] of Object.entries(files)) {
  if (process.argv.includes("--check")) {
    let cur = "";
    try {
      cur = readFileSync(p, "utf8");
    } catch {}
    if (cur !== c) (console.error(`${p} is stale`), stale++);
  } else writeFileSync(p, c);
}
if (stale) (console.error("run bun tools/workshop/module-pages.ts"), process.exit(1));
console.log(process.argv.includes("--check") ? `${Object.keys(files).length} module pages are current` : `wrote ${Object.keys(files).length} module pages`);
